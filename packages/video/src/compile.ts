// ScriptOutline -> VideoProject (script.md, scenes.js, video.json and friends).
// This is the seam for LLM-written scripts: produce a ScriptOutline, call buildProject().
import { FREE_TIER, videoAllowed } from "@cg/core";
import type { LearningPath, VideoKind, VideoProject } from "@cg/core";
import { estimateSec, outlineProblems, VideoPlanError } from "./outline.js";
import type { OutlineScene, ScriptOutline } from "./outline.js";
import { BASE_LIB, SLIDES_LIB, WHITEBOARD_LIB } from "./runtime.js";

export class VideoLimitError extends Error {}

export type RenderableKind = Exclude<VideoKind, "none">;

export interface BuildOptions {
  kind: RenderableKind;
  /** Learning path of the plan. When given, the kind must be allowed for it (VIDEO_BY_PATH). */
  path?: LearningPath;
  /** Hard limit in seconds on the estimated length. Defaults to the free tier (300 s). */
  maxSec?: number;
  /** User-supplied images and clips, keyed by project path, e.g. "assets/bench.mp4". */
  media?: Record<string, Uint8Array>;
  /** explainroo size name or WIDTHxHEIGHT. Default "youtube"; "shorts" for vertical. */
  size?: string;
  /** explainroo shows a small watermark by default. Off unless asked for. */
  watermark?: string | false;
}

const enc = (s: string) => new TextEncoder().encode(s);
const FRAME: Partial<Record<RenderableKind, string>> = { demo: "window", screen: "browser" };

export const WHITEBOARD_LOOK = {
  extends: "paper",
  name: "whiteboard",
  bg: "#ffffff",
  surface: "#ffffff",
  ink: "#1b2340",
  muted: "#586078",
  accent: "red",
  background: "plain",
  transition: "fade",
  music: "calm",
  colors: { red: "#d62828", blue: "#1f5fd1", green: "#1b8a3d", orange: "#e8590c", yellow: "#f2b705", purple: "#7b3fb5", teal: "#0f8b8d" },
};

function videoJson(o: ScriptOutline, opt: BuildOptions): object {
  const base: Record<string, unknown> = {
    title: o.title,
    size: opt.size ?? "youtube",
    voice: "af_heart",
    captions: "auto",
    watermark: opt.watermark ?? false,
    cover: "auto",
  };
  switch (opt.kind) {
    case "whiteboard": return { ...base, theme: "look.json", boil: 3, music: { style: "calm", volume: 0.08 }, sfx: true };
    case "slides": return { ...base, theme: "clean", music: false, sfx: "minimal", transition: "fade" };
    case "demo":
    case "screen": return { ...base, theme: "clean", music: { style: "calm", volume: 0.08 }, sfx: "minimal" };
    default: return { ...base, theme: "clean", music: { style: "upbeat", volume: 0.1 }, sfx: true };
  }
}

function sceneData(sc: OutlineScene, kind: RenderableKind, media: Record<string, Uint8Array>): Record<string, unknown> {
  const { type, ...data } = sc.visual as { type: string } & Record<string, unknown>;
  if (type !== "media") return data;
  const asset = data.asset as string | undefined;
  if (asset && !(asset in media)) throw new VideoPlanError(`scene "${sc.id}" uses asset "${asset}" that was not supplied`);
  return { title: data.title, caption: data.caption, src: asset ?? null, frame: FRAME[kind] ?? "window", url: "" };
}

export function buildScenesJs(o: ScriptOutline, kind: RenderableKind, media: Record<string, Uint8Array> = {}): string {
  const libs = [BASE_LIB, ...(kind === "whiteboard" ? [WHITEBOARD_LIB] : []), ...(kind === "slides" ? [SLIDES_LIB] : [])].join("\n");
  const overrides = kind === "whiteboard" ? "WB" : kind === "slides" ? "SL" : "{}";
  const total = o.scenes.length;
  const fns = o.scenes.map((sc, i) => {
    const data = JSON.stringify(sceneData(sc, kind, media));
    const meta = JSON.stringify({ course: o.courseLabel, n: i + 1, total });
    return `  '${sc.id}'(s) { R.${sc.visual.type}(s, ${data}, ${meta}); },`;
  });
  return [
    `// Generated by @cg/video (${kind}). Edit script.md and scenes.js by hand if you like; explainroo reads them as they are.`,
    libs,
    `const R = Object.assign({}, BASE, ${overrides});`,
    "export default {",
    ...fns,
    "};",
    "",
  ].join("\n");
}

export function buildScriptMd(o: ScriptOutline): string {
  const clean = (t: string) => t.replace(/["{}\n]/g, " ").trim().slice(0, 60);
  const parts = [`# ${clean(o.title) || "Video"}`, ""];
  o.scenes.forEach((sc, i) => {
    const attrs = [sc.chapter ? `chapter="${clean(sc.chapter)}"` : "", i === o.scenes.length - 1 ? "hold=1.1" : ""].filter(Boolean);
    parts.push(`## ${sc.id}${attrs.length ? ` {${attrs.join(" ")}}` : ""}`, sc.narration.trim(), "");
  });
  return parts.join("\n");
}

/** The seam: a script outline in, an explainroo project out. Throws VideoPlanError / VideoLimitError. */
export function buildProject(outline: ScriptOutline, opt: BuildOptions): VideoProject {
  if (opt.path && !videoAllowed(opt.path, opt.kind)) throw new VideoPlanError(`video kind "${opt.kind}" is not allowed on the "${opt.path}" learning path`);
  const problems = outlineProblems(outline);
  if (problems.length) throw new VideoPlanError(`invalid script outline:\n- ${problems.join("\n- ")}`);
  const media = opt.media ?? {};
  for (const p of Object.keys(media)) {
    if (!/^assets\/[\w.\- ]+$/.test(p)) throw new VideoPlanError(`media path "${p}" must look like assets/name.ext`);
  }
  const maxSec = opt.maxSec ?? FREE_TIER.videoSecondsPerMonth;
  const estimatedSec = estimateSec(outline.scenes.map((s) => s.narration));
  if (estimatedSec > maxSec) throw new VideoLimitError(`estimated length ${estimatedSec.toFixed(0)} s is over the ${maxSec} s limit`);

  const assets: Record<string, Uint8Array> = { ...media, "video.json": enc(JSON.stringify(videoJson(outline, opt), null, 2) + "\n") };
  if (opt.kind === "whiteboard") assets["look.json"] = enc(JSON.stringify(WHITEBOARD_LOOK, null, 2) + "\n");
  return { scriptMd: buildScriptMd(outline), scenesJs: buildScenesJs(outline, opt.kind, media), assets, estimatedSec };
}
