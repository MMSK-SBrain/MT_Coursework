import { hourBlockProblems, outcomeVerbProblem, uncoveredOutcomes, type Course } from "@cg/core";
import type { ImportResult } from "./courses/common.js";

export interface RuleWarnings {
  verb: { id: string; text: string; problem: string }[];
  hours: { session: string; problems: string[] }[];
  sessionsWithBlocks: number;
  sessionsClean: number;
  uncovered: string[];
}

export function runRules(course: Course): RuleWarnings {
  const verb = course.outcomes.flatMap((o) => { const p = outcomeVerbProblem(o); return p ? [{ id: o.id, text: o.text, problem: p }] : []; });
  const plan = course.plans[0];
  const hours: RuleWarnings["hours"] = [];
  let withBlocks = 0;
  for (const s of plan?.sessions ?? []) {
    if (!s.blocks.length) continue;
    withBlocks += 1;
    const problems = hourBlockProblems(s.blocks, s.minutes);
    if (problems.length) hours.push({ session: `${s.id} ${s.title}`, problems });
  }
  return { verb, hours, sessionsWithBlocks: withBlocks, sessionsClean: withBlocks - hours.length, uncovered: plan ? uncoveredOutcomes(course, plan) : [] };
}

const MAX = 12;
const clip = (s: string, n = 110) => (s.length > n ? s.slice(0, n - 1) + "…" : s);

export function renderReport(r: ImportResult, w: RuleWarnings): string {
  const c = r.course;
  const L: string[] = [];
  L.push(`# Import report: ${c.brief.title} (${c.brief.code ?? c.slug})`, "");
  L.push("Generated by `@cg/importer`; do not edit by hand (re-run `pnpm --filter @cg/importer run import <course-dir>`).", "");
  L.push("## Imported", "", ...r.imported.map((x) => `- ${x}`), `- brief: ${c.brief.contactHours} contact hours, level ${c.brief.level}, ${c.brief.textbooks.length} textbook/reference entries`, "- all outcomes marked `origin: \"handout\"`; all provenance `model: \"import\"`; roles and fit empty; `outcomesFrozenAt` not set", "");
  if (r.notes.length) L.push("## Mapping decisions", "", ...r.notes.map((x) => `- ${x}`), "");
  L.push("## Gaps (not invented)", "", ...r.gaps.map((x) => `- ${x}`), "");
  L.push("## Rule warnings", "");
  L.push(`- Outcome verbs (\`outcomeVerbProblem\`): ${w.verb.length} of ${c.outcomes.length} outcomes flagged.`);
  const byReason = new Map<string, number>();
  for (const v of w.verb) { const k = v.problem.startsWith("starts with the unmeasurable") ? "unmeasurable verb" : `verb not in the core list for the inferred level`; byReason.set(k, (byReason.get(k) ?? 0) + 1); }
  for (const [k, n] of byReason) L.push(`  - ${n} x ${k}`);
  const lead = new Map<string, number>();
  for (const v of w.verb) { const k = v.text.trim().split(/\s+/)[0]!.toLowerCase(); lead.set(k, (lead.get(k) ?? 0) + 1); }
  const top = [...lead].sort((a, b) => b[1] - a[1]).slice(0, 12).map(([k, n]) => `${k} (${n})`).join(", ");
  if (top) L.push(`  - most common leading verbs flagged (candidates for the core verb table): ${top}`);
  for (const v of w.verb.slice(0, MAX)) L.push(`  - ${v.id}: "${clip(v.text, 80)}" ${v.problem}`);
  if (w.verb.length > MAX) L.push(`  - ... and ${w.verb.length - MAX} more`);
  L.push(`- Hour blocks (\`hourBlockProblems\`): ${w.sessionsWithBlocks} sessions have blocks; ${w.sessionsClean} are clean, ${w.hours.length} have problems. Blocks are placed exactly as the framework states its minutes, so a phase list that does not add up to the session length shows here.`);
  for (const h of w.hours.slice(0, MAX)) L.push(`  - ${h.session}: ${h.problems[0]}${h.problems.length > 1 ? ` (+${h.problems.length - 1} more)` : ""}`);
  if (w.hours.length > MAX) L.push(`  - ... and ${w.hours.length - MAX} more sessions`);
  L.push(`- Coverage (\`uncoveredOutcomes\`): ${w.uncovered.length ? `${w.uncovered.length} outcome(s) taught by no session: ${w.uncovered.slice(0, 20).join(", ")}` : "every outcome is taught by at least one session"}.`, "");
  return L.join("\n");
}
